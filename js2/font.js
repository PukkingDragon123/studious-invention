class BitmapFont {
  constructor(glyphs, gw, gh, adv, lh) {
    this.glyphs = glyphs; this.gw = gw; this.gh = gh; this.adv = adv; this.lh = lh;
    this.cache = new Map();
  }
  rows(ch) {
    let r = this.glyphs[ch];
    if (!r) r = this.glyphs[ch.toUpperCase()] || this.glyphs[ch.toLowerCase()] || this.glyphs['?'];
    return r.split('|');
  }
  glyph(ch, color) {
    const key = ch + '|' + color;
    let c = this.cache.get(key); if (c) return c;
    const rows = this.rows(ch);
    c = document.createElement('canvas'); c.width = this.gw; c.height = this.gh;
    const g = c.getContext('2d'); g.fillStyle = color;
    for (let y = 0; y < rows.length; y++) for (let x = 0; x < rows[y].length; x++) if (rows[y][x] === '#') g.fillRect(x, y, 1, 1);
    this.cache.set(key, c); return c;
  }
  width(str, scale = 1, tracking = 0) { return Math.max(0, str.length * (this.adv + tracking) * scale - tracking * scale); }
  draw(ctx, str, x, y, color = '#fff', scale = 1, tracking = 0) {
    let cx = x; const step = (this.adv + tracking) * scale;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch !== ' ') {
        const g = this.glyph(ch, color);
        if (scale === 1) ctx.drawImage(g, Math.round(cx), Math.round(y));
        else ctx.drawImage(g, Math.round(cx), Math.round(y), this.gw * scale, this.gh * scale);
      }
      cx += step;
    }
  }
}

