const Font = {
  gw: 5, gh: 7, adv: 6, lh: 9,
  cache: new Map(),
  // Pre-render a glyph in a color into a small canvas
  glyph(ch, color) {
    const key = ch + '|' + color;
    let c = this.cache.get(key);
    if (c) return c;
    let rows = FONT_GLYPHS[ch];
    if (!rows) rows = FONT_GLYPHS[ch.toUpperCase()] || FONT_GLYPHS['?'];
    rows = rows.split('|');
    c = document.createElement('canvas'); c.width = this.gw; c.height = this.gh;
    const g = c.getContext('2d'); g.fillStyle = color;
    for (let y = 0; y < rows.length; y++) for (let x = 0; x < rows[y].length; x++) if (rows[y][x] === '#') g.fillRect(x, y, 1, 1);
    this.cache.set(key, c);
    return c;
  },
  width(str, scale = 1) { return str.length * this.adv * scale - scale; },
  draw(ctx, str, x, y, color = '#fff', scale = 1) {
    ctx.imageSmoothingEnabled = false;
    let cx = x;
    const s = this.adv * scale;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch !== ' ') {
        const g = this.glyph(ch, color);
        if (scale === 1) ctx.drawImage(g, Math.round(cx), Math.round(y));
        else ctx.drawImage(g, Math.round(cx), Math.round(y), this.gw * scale, this.gh * scale);
      }
      cx += s;
    }
  }
};
